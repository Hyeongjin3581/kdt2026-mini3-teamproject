# ─────────────────────────────────────────────
# 4-2. 민감도: 기준 연도를 2022·2023·2024로 바꿔도 결과가 비슷한가 (중간 시나리오 = 격차 50% 해소)
#      각 연도의 반납률 격차·면허 소지자·사상자·단가를 모두 같은 해 값으로 맞춘다. 금액은 각 연도 기준 금액이라 더하거나 평균 내지 않는다.
# ─────────────────────────────────────────────
민감 = []
for 연도 in [2022, 2023, 2024]:
    t = 결합[결합['연도'] == 연도].copy()
    t['유형'] = np.where(t['시도명'].str.contains('특별시|광역시|특별자치시'), '특별·광역시', '도')
    g = t.groupby('유형')[['반납건수', '65세이상인구']].sum()
    g['반납률'] = g['반납건수'] / g['65세이상인구'] * 1000
    격차y = g.loc['특별·광역시', '반납률'] - g.loc['도', '반납률']
    추가y = 격차y * 0.5 * g.loc['도', '65세이상인구'] / 1000
    위험y = TAAS[연도]['사고'] / 고령면허[연도]
    _, 건당y = 사고1건당(연도)
    민감.append({'기준 연도': 연도, '반납률 격차(건)': round(격차y, 2), '추가 반납(명)': round(추가y),
                '면허 1만 명당 사고': round(위험y * 1e4, 2), '사고 1건당 비용(만 원)': round(건당y / 1e4),
                '사고 감소 상한(건)': round(추가y * 위험y, 1), '비용 절감 상한(억 원, 해당 연도 기준)': round(추가y * 위험y * 건당y / 1e8, 1)})
민감 = pd.DataFrame(민감)
print('\n[4] 기준 연도별 민감도 (중간 시나리오)')
print(민감.to_string(index=False))

