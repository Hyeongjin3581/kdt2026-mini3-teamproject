# 기존 기대 효과(E_결합.py 6-1 ~ 6-3)의 문제
#   ① 반납률 하위 5개 시도를 '전국 평균'까지 올린다는 목표가 분석 결과와 연결되지 않음
#   ② 사고 감소 = 추가 반납자 × 65세 이상 '인구' 1만 명당 사고 → 면허 없는 어르신까지 분모에 포함
#   ③ A-3(반납률이 높아도 사고가 적지 않음, 기각)과 반대로 "반납 → 사고 감소"를 전제
#
# 재설계 방향
#   ① 반납 목표: 우리 결과(도 지역 반납률이 대도시보다 3년 내내 낮음)에서 출발 → 격차를 25 / 50 / 100% 줄이는 3가지 시나리오
#   ② 사고 위험: KOSIS 고령 면허 소지자 수로 '면허 소지자 1만 명당 사고'를 계산해 상한으로 사용
#   ③ A-3 반영: 반납 1명당 사고 감소를 0(하한) ~ 면허 소지자 평균(상한) 범위로 제시
#   ④ (2차 보완) 모든 입력값을 공식 통계로: 사고·사상자는 TAAS, 면허 소지자는 KOSIS, 비용 단가는 한국도로교통공단 공식 보고서(같은 해 단가).
#      비용은 '사망 비용 × 치사율' 대신, 고령운전자 사고의 실제 사상자 구성(사망·중상·경상·부상신고)으로 1건당 비용을 계산한다.
#      남는 가정은 하나: "추가로 반납하는 어르신의 사고 위험 = 고령 면허 소지자 평균"(상한). 하한은 A-3 결과에 따라 0건.

