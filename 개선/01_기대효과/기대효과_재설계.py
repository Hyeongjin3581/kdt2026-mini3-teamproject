# KOSIS 「운전면허소지자현황(연령대별)」 경찰청, DT_13201_A002 (2025-12-11 갱신)
#   65세 ~ 99세 이상 '총계' 열을 연도별로 더한 값. 시도별 표(DT_13201_A005)에는 연령 구분이 없어 전국 값만 사용한다.
고령면허 = pd.Series({2022: 4_387_358, 2023: 4_747_426, 2024: 5_166_386}, name='고령면허소지자')

# TAAS 교통사고분석시스템 (한국도로교통공단) 「시도 시군구별·월별 (노인운전자) 교통사고」 전국 합계
#   https://taas.koroad.or.kr/sta/acs/gus/selectOdsnDrverTfcacd.do?menuId=WEB_KMP_OVT_MVT_TAS_ODT
#   상세보기(통계분석)에서 연도별로 중상자·경상자·부상신고자 항목을 추가해 조회한 값
TAAS = {
    2022: {'사고': 34_652, '사망': 735, '중상': 9_746, '경상': 36_602, '부상신고': 2_933},     # 부상 49,281
    2023: {'사고': 39_614, '사망': 745, '중상': 11_144, '경상': 41_407, '부상신고': 3_516},    # 부상 56,067
    2024: {'사고': 42_369, '사망': 761, '중상': 11_583, '경상': 44_442, '부상신고': 3_751},    # 부상 59,776
}
for 연도, 부상 in [(2022, 49_281), (2023, 56_067), (2024, 59_776)]:
    assert TAAS[연도]['중상'] + TAAS[연도]['경상'] + TAAS[연도]['부상신고'] == 부상

# 한국도로교통공단 「도로교통 사고비용의 추계와 평가」 사상자 피해종별 평균비용 (사회기관비용 포함, 단위: 천 원 → 원)
#   TAAS 통계보고서 > 도로교통사고비용의 추계 게시판의 공식 보고서 PDF
#   2022: 2023년판 <표 5-4> / 2023: 2024년판 <표 5-4> / 2024: 2025년판 <표 30>
단가표 = {
    2022: {'사망': 533_786.8, '중상': 68_898.9, '경상': 5_200.3, '부상신고': 2_682.0},
    2023: {'사망': 552_717.2, '중상': 69_606.7, '경상': 4_833.0, '부상신고': 2_583.2},
    2024: {'사망': 551_525.5, '중상': 69_066.8, '경상': 4_886.9, '부상신고': 2_564.8},
}
단가표 = {y: {k: v * 1000 for k, v in d.items()} for y, d in 단가표.items()}


def 사고1건당(연도):
    """고령운전자 사고 1건당 인적피해 비용 = Σ(사상자 수 × 같은 해 1인당 비용) ÷ 사고 건수 (물적피해 제외)"""
    피해 = {k: TAAS[연도][k] * 단가표[연도][k] for k in 단가표[연도]}
    return 피해, sum(피해.values()) / TAAS[연도]['사고']


기준연도 = 2024
인적피해, 건당비용 = 사고1건당(기준연도)
단가 = 단가표[기준연도]
TAAS_2024 = TAAS[기준연도]
건당사망 = TAAS_2024['사망'] / TAAS_2024['사고']
print(f'[0] 고령운전자 사고 1건당 인적피해 비용 ({기준연도} 사상자 × {기준연도} 단가)')
for k, v in 인적피해.items():
    print(f'  {k}: {TAAS_2024[k]:,}명 × {단가[k] / 1e4:,.1f}만 원 = {v / 1e8:,.1f}억 원')
print(f'  합계 {sum(인적피해.values()) / 1e8:,.1f}억 원 ÷ {TAAS_2024["사고"]:,}건 = 1건당 {건당비용 / 1e4:,.0f}만 원')

# ─────────────────────────────────────────────
# 2. 분모 바꾸기: 인구 기준 vs 면허 소지자 기준
# ─────────────────────────────────────────────
전국 = 결합.groupby('연도')[['65세이상인구', '반납건수']].sum()
전국['고령사고'] = 사고.groupby('연도')['고령사고건수'].sum()
전국['고령사망'] = 사고.groupby('연도')['고령사망자수'].sum()
전국['고령면허소지자'] = 고령면허
전국['면허보유율(%)'] = 전국['고령면허소지자'] / 전국['65세이상인구'] * 100
전국['반납률_인구천명당'] = 전국['반납건수'] / 전국['65세이상인구'] * 1000
전국['반납률_면허천명당'] = 전국['반납건수'] / 전국['고령면허소지자'] * 1000
전국['사고_인구만명당'] = 전국['고령사고'] / 전국['65세이상인구'] * 1e4
전국['사고_면허만명당'] = 전국['고령사고'] / 전국['고령면허소지자'] * 1e4
전국['치사율(%)'] = 전국['고령사망'] / 전국['고령사고'] * 100
변화율 = (전국.loc[2024] / 전국.loc[2022] - 1) * 100

print('[1] 분모별 지표')
print(전국.round(2).T.to_string())
print('\n2022 → 2024 변화율(%)')
print(변화율.round(1).to_string())

# ─────────────────────────────────────────────
# 3. 반납 목표: 도 지역 반납률을 대도시 수준으로
# ─────────────────────────────────────────────
y24 = 결합[결합['연도'] == 2024].copy()
y24['유형'] = np.where(y24['시도명'].str.contains('특별시|광역시|특별자치시'), '특별·광역시', '도')
유형 = y24.groupby('유형')[['반납건수', '65세이상인구']].sum()
유형['반납률'] = 유형['반납건수'] / 유형['65세이상인구'] * 1000
격차 = 유형.loc['특별·광역시', '반납률'] - 유형.loc['도', '반납률']
