# ─────────────────────────────────────────────
# 면허 소지자 1명당 연간 사고 = TAAS 2024 사고 ÷ KOSIS 2024 고령 면허 소지자 (계산값)
면허1명당사고 = TAAS_2024['사고'] / 고령면허[2024]
print(f'\n고령 면허 소지자 1만 명당 사고 = {TAAS_2024["사고"]:,} ÷ {고령면허[2024]:,} × 10,000 = {면허1명당사고 * 1e4:.2f}건')

행 = []
for 이름, 비율 in [('보수적', 0.25), ('중간', 0.50), ('낙관적', 1.00)]:
    추가반납 = 격차 * 비율 * 도인구 / 1000
    상한사고 = 추가반납 * 면허1명당사고
    행.append({'시나리오': 이름, '격차 해소': f'{비율:.0%}', '추가 반납(명)': round(추가반납),
              '사고 감소(건/년)': f'0 ~ {상한사고:.1f}',
              '사망 감소(명/년)': f'0 ~ {상한사고 * 건당사망:.2f}',
              '인적피해 비용 절감(억 원/년)': f'0 ~ {상한사고 * 건당비용 / 1e8:.1f}',
              '_상한사고': 상한사고, '_상한비용': 상한사고 * 건당비용 / 1e8})
시나리오 = pd.DataFrame(행)
보기 = 시나리오.drop(columns=['_상한사고', '_상한비용'])

# 기존 방식 (E_결합.py 6-1 ~ 6-2 재현)
전국반납률 = 전국.loc[2024, '반납률_인구천명당']
