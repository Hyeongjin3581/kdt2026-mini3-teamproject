# [개인 보완] 회고 ③ 기대 효과 재설계
# 실행: 저장소 최상위에서 python "개선/01_기대효과/기대효과_재설계.py"
#
# 기존 기대 효과(E_결합.py 6-1 ~ 6-3)의 문제
#   ① 반납률 하위 5개 시도를 '전국 평균'까지 올린다는 목표가 분석 결과와 연결되지 않음
#   ② 사고 감소 = 추가 반납자 × 65세 이상 '인구' 1만 명당 사고 → 면허 없는 어르신까지 분모에 포함
#   ③ A-3(반납률이 높아도 사고가 적지 않음, 기각)과 반대로 "반납 → 사고 감소"를 전제
#
# 재설계 방향
#   ① 반납 목표: 우리 결과(도 지역 반납률이 대도시보다 3년 내내 낮음)에서 출발 → 격차를 25 / 50 / 100% 줄이는 3가지 시나리오
#   ② 사고 위험: KOSIS 고령 면허 소지자 수로 '면허 소지자 1만 명당 사고'를 계산해 상한으로 사용
#   ③ A-3 반영: 반납 1명당 사고 감소를 0(하한) ~ 면허 소지자 평균(상한) 범위로 제시

import numpy as np
import pandas as pd
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import seaborn as sns

plt.rc('font', family='Malgun Gothic')
plt.rcParams['axes.unicode_minus'] = False
sns.set_theme(font='Malgun Gothic', rc={'axes.unicode_minus': False}, style='whitegrid')

출력 = '개선/01_기대효과'

# ─────────────────────────────────────────────
# 1. 데이터
# ─────────────────────────────────────────────
결합 = pd.read_csv('data/merge/결합테이블.csv')
사고 = pd.read_csv('data/정제_A_사고.csv')

# KOSIS 「운전면허소지자현황(연령대별)」 경찰청, DT_13201_A002 (2025-12-11 갱신)
#   65세 ~ 99세 이상 '총계' 열을 연도별로 더한 값. 시도별 표(DT_13201_A005)에는 연령 구분이 없어 전국 값만 사용한다.
고령면허 = pd.Series({2022: 4_387_358, 2023: 4_747_426, 2024: 5_166_386}, name='고령면허소지자')

# 사망 1명당 사회적 비용 (도로교통공단, 2022년 기준 · 2024.02 발표) — 외부 값
사망1명비용 = 533_790_000

# ─────────────────────────────────────────────
# 2. 분모 바꾸기: 인구 기준 vs 면허 소지자 기준
# ─────────────────────────────────────────────
전국 = 결합.groupby('연도')[['65세이상인구', '반납건수']].sum()
전국['고령사고'] = 사고.groupby('연도')['고령사고건수'].sum()
전국['고령사망'] = 사고.groupby('연도')['고령사망자수'].sum()
전국['고령면허소지자'] = 고령면허
전국['면허보유율(%)'] = 전국['고령면허소지자'] / 전국['65세이상인구'] * 100
전국['반납률_인구천명당'] = 전국['반납건수'] / 전국['65세이상인구'] * 1000
전국['반납률_면허천명당'] = 전국['반납건수'] / 전국['고령면허소지자'] * 1000
전국['사고_인구만명당'] = 전국['고령사고'] / 전국['65세이상인구'] * 1e4
전국['사고_면허만명당'] = 전국['고령사고'] / 전국['고령면허소지자'] * 1e4
전국['치사율(%)'] = 전국['고령사망'] / 전국['고령사고'] * 100
변화율 = (전국.loc[2024] / 전국.loc[2022] - 1) * 100

print('[1] 분모별 지표')
print(전국.round(2).T.to_string())
print('\n2022 → 2024 변화율(%)')
print(변화율.round(1).to_string())

# ─────────────────────────────────────────────
# 3. 반납 목표: 도 지역 반납률을 대도시 수준으로
# ─────────────────────────────────────────────
y24 = 결합[결합['연도'] == 2024].copy()
y24['유형'] = np.where(y24['시도명'].str.contains('특별시|광역시|특별자치시'), '특별·광역시', '도')
유형 = y24.groupby('유형')[['반납건수', '65세이상인구']].sum()
유형['반납률'] = 유형['반납건수'] / 유형['65세이상인구'] * 1000
격차 = 유형.loc['특별·광역시', '반납률'] - 유형.loc['도', '반납률']
도인구 = 유형.loc['도', '65세이상인구']

print('\n[2] 2024년 지역 유형별 반납률 (65세 이상 천 명당)')
print(유형.round(2).to_string())
print(f'격차: {격차:.2f}건')

# ─────────────────────────────────────────────
# 4. 시나리오: 추가 반납 × 반납 1명당 사고 감소(하한 0 ~ 상한 면허 소지자 평균)
# ─────────────────────────────────────────────
사고위험 = {
    '하한 (A-3: 관계 확인 안 됨)': 0.0,
    '중간 (인구 기준, 기존 방식)': 전국.loc[2024, '사고_인구만명당'] / 1e4,
    '상한 (면허 소지자 평균)': 전국.loc[2024, '사고_면허만명당'] / 1e4,
}
치사율 = 전국.loc[2024, '치사율(%)'] / 100

행 = []
for 이름, 비율 in [('보수적', 0.25), ('중간', 0.50), ('낙관적', 1.00)]:
    추가반납 = 격차 * 비율 * 도인구 / 1000
    r = {'시나리오': 이름, '격차 해소': f'{비율:.0%}', '추가 반납(명)': round(추가반납)}
    for k, 위험 in 사고위험.items():
        r[f'사고 감소 · {k}'] = round(추가반납 * 위험, 1)
    상한사고 = 추가반납 * 사고위험['상한 (면허 소지자 평균)']
    r['사망 비용 절감 상한(억 원)'] = round(상한사고 * 치사율 * 사망1명비용 / 1e8, 1)
    행.append(r)
시나리오 = pd.DataFrame(행)

# 기존 방식 (E_결합.py 6-1 ~ 6-2 재현)
전국반납률 = 전국.loc[2024, '반납률_인구천명당']
하위 = y24.nsmallest(len(y24) // 3, '반납률').copy()
하위['추가'] = (전국반납률 - 하위['반납률']) * 하위['65세이상인구'] / 1000
기존반납 = 하위['추가'].sum()
기존사고 = (하위['추가'] * 하위['고령사고_만명당'] / 1e4).sum()

print('\n[3] 시나리오 (2024년 기준)')
print(시나리오.to_string(index=False))
print(f'\n[참고] 기존 방식: 반납률 하위 {len(하위)}개 시도 → 전국 평균, 추가 반납 {기존반납:,.0f}명 · 사고 감소 {기존사고:.1f}건')

# ─────────────────────────────────────────────
# 5. 결과 저장
# ─────────────────────────────────────────────
def 마크다운(df, index=True):
    """tabulate 없이 DataFrame을 마크다운 표로 바꾼다."""
    d = df.reset_index().rename(columns={'index': '지표'}) if index else df
    def 칸(v):
        return f'{v:,.2f}'.rstrip('0').rstrip('.') if isinstance(v, float) else (f'{v:,}' if isinstance(v, (int, np.integer)) else str(v))
    줄 = ['| ' + ' | '.join(map(str, d.columns)) + ' |', '|' + '---|' * len(d.columns)]
    줄 += ['| ' + ' | '.join(칸(v) for v in r) + ' |' for r in d.itertuples(index=False)]
    return '\n'.join(줄)


표1 = 전국[['65세이상인구', '고령면허소지자', '면허보유율(%)', '반납건수', '반납률_인구천명당', '반납률_면허천명당',
          '고령사고', '사고_인구만명당', '사고_면허만명당']].T
with open(f'{출력}/결과표.md', 'w', encoding='utf-8') as f:
    f.write('# 회고 ③ 기대 효과 재설계 — 결과표\n\n')
    f.write('`기대효과_재설계.py` 실행 결과 (2024년 기준 시나리오)\n\n')
    f.write('## 1. 분모별 지표\n\n')
    f.write(표1.round(2).pipe(마크다운) + '\n\n')
    f.write('2022 → 2024 변화율(%)\n\n')
    f.write(변화율[['65세이상인구', '고령면허소지자', '반납건수', '반납률_인구천명당', '반납률_면허천명당',
                  '고령사고', '사고_인구만명당', '사고_면허만명당']].round(1).to_frame('변화율(%)').pipe(마크다운) + '\n\n')
    f.write('## 2. 2024년 지역 유형별 반납률\n\n')
    f.write(유형.round(2).pipe(마크다운) + f'\n\n격차: {격차:.2f}건 (65세 이상 천 명당)\n\n')
    f.write('## 3. 시나리오\n\n')
    f.write(마크다운(시나리오, index=False) + '\n\n')
    f.write(f'기존 방식: 반납률 하위 {len(하위)}개 시도 → 전국 평균, 추가 반납 {기존반납:,.0f}명 · 사고 감소 {기존사고:.1f}건\n')

# 그래프: 시나리오별 추가 반납(왼쪽) · 사고 감소 범위(오른쪽)
fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(13, 5.5))
색 = ['#9AA5B1', '#4C72B0', '#1F4E79']
막대 = ax1.bar(시나리오['시나리오'], 시나리오['추가 반납(명)'], color=색, width=0.6)
ax1.bar_label(막대, labels=[f'{v:,}명' for v in 시나리오['추가 반납(명)']], padding=3, fontsize=11)
ax1.set_title(f'도 지역 반납률 격차({격차:.2f}건) 해소 시 추가 반납', fontsize=12)
ax1.set_ylim(0, 시나리오['추가 반납(명)'].max() * 1.18)
ax1.set_xticks(range(3), [f'{n}\n(격차 {p} 해소)' for n, p in zip(시나리오['시나리오'], 시나리오['격차 해소'])])
ax1.grid(axis='x', visible=False)

키 = list(사고위험)
for i, (_, r) in enumerate(시나리오.iterrows()):
    하, 중, 상 = r[f'사고 감소 · {키[0]}'], r[f'사고 감소 · {키[1]}'], r[f'사고 감소 · {키[2]}']
    ax2.plot([i, i], [하, 상], color=색[i], linewidth=10, solid_capstyle='butt', alpha=0.85)
    ax2.plot(i, 중, 'o', color='white', markeredgecolor='black', markersize=9, zorder=3)
    ax2.text(i + 0.12, 상, f'상한 {상:.0f}건', va='center', fontsize=10)
    ax2.text(i + 0.12, 중, f'중간 {중:.0f}건', va='center', fontsize=10)
ax2.set_xticks(range(3), 시나리오['시나리오'])
ax2.set_xlim(-0.5, 2.9)
ax2.set_ylim(0, 시나리오[f'사고 감소 · {키[2]}'].max() * 1.15)
ax2.set_title('연간 고령운전자 사고 감소 범위 (하한 0건 = A-3 결과)', fontsize=12)
ax2.set_ylabel('건')
ax2.grid(axis='x', visible=False)
fig.suptitle('기대 효과 재설계: 분석 결과(지역 유형 격차) 기반 시나리오 · 2024년 기준', fontsize=14, fontweight='bold')
plt.tight_layout()
fig.savefig(f'{출력}/기대효과_시나리오.png', dpi=150, facecolor='white')
print(f'\n저장: {출력}/결과표.md, {출력}/기대효과_시나리오.png')
