# [개인 보완] 회고 ① 크롤링 확장 — A안 (3) 관련성 판정 + 대책 유형 분류 (본문 기반)
# 실행: 저장소 최상위에서 python "개선/04_크롤링확장/03_분류.py"
#
# 팀 D는 22건을 사람이 직접 분류했다(최종 6건). 기사가 늘어나 같은 기준표를 '키워드 사전'으로 바꿔 본문에 적용하고,
# 결과는 사람이 검수한다(검수표 CSV). 기준표는 팀 D 4-4 와 같다.
#   ① 운전자·차량  ② 면허·적성(자진반납 포함)  ③ 보행 환경  ④ 이동권·대중교통  ⑤ 기타(사고 분석·홍보 등)
#   제외: 통계 발표, 복지·주거·인구정책 일반, 단어만 겹치는 기사
#
# 판정 순서
#   1) 제외: 통계 발표(통계청·국가데이터처, 제목에 '통계'), 본문에 고령자 '교통' 관련 표현이 거의 없는 기사
#   2) 유형: 본문에서 유형별 핵심어가 나온 횟수를 세어, 가장 많은 유형을 '주 유형'으로 하고 2회 이상 나온 유형은 모두 '관련 유형'으로 표시
#   3) 같은 날·같은 부처 발표는 1건으로 묶는다 (팀 D와 같은 규칙)

import re
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import seaborn as sns

plt.rc('font', family='Malgun Gothic')
plt.rcParams['axes.unicode_minus'] = False
sns.set_theme(font='Malgun Gothic', rc={'axes.unicode_minus': False}, style='whitegrid')

출력 = '개선/04_크롤링확장'
d = pd.read_csv(f'{출력}/정책브리핑_본문_2015_2025.csv')
d['본문'] = d['본문'].fillna('')
d['전체글'] = d['제목'].fillna('') + ' ' + d['요약'].fillna('') + ' ' + d['본문']
d['연도'] = d['날짜'].str[:4].astype(int)

# 1) 관련성: 고령자 + 교통 표현
고령교통 = r'고령\s?운전자|노인\s?운전자|어르신\s?운전|고령자\s?운전|면허\s?(자진)?\s?반납|자진\s?반납|조건부\s?(운전)?\s?면허|적성\s?검사|노인\s?보호\s?구역|노인\s?보행|고령\s?보행|어르신\s?보행|보행\s?노인|고령자\s?교통|노인\s?교통|어르신\s?교통|교통\s?약자|이동권'
d['관련어수'] = d['전체글'].str.count(고령교통)
통계발표 = d['부처'].fillna('').str.contains('통계청|국가데이터처') | d['제목'].str.contains('통계')
# 본문을 못 받은 기사(첨부가 hwp 등)는 제목+요약만 있으므로 기준을 1회로 낮춘다 (검수 중 발견: 2020 고령자 교통안전 종합계획 등이 빠졌음)
본문없음 = d['본문'].str.len() < 50
기준 = np.where(본문없음, 1, 3)
d['제외사유'] = np.select([통계발표, d['관련어수'] < 기준], ['통계 발표', '고령자 교통 내용 거의 없음'], '')

# 2) 유형 핵심어 사전
사전 = {
    '① 운전자·차량': r'페달\s?오조작|오조작\s?방지|첨단\s?안전\s?장치|비상\s?자동\s?제동|안전\s?장치\s?(장착|지원)|고령\s?운전자\s?(안전\s?)?교육|운전\s?능력',
    '② 면허·적성': r'조건부\s?(운전)?\s?면허|적성\s?검사|인지\s?기능\s?검사|면허\s?(자진)?\s?반납|자진\s?반납|면허\s?갱신|갱신\s?주기',
    '③ 보행 환경': r'노인\s?보호\s?구역|보행자\s?(교통)?\s?사고|횡단\s?보도|무단\s?횡단|보행\s?안전|사고\s?다발\s?(지역|지점)|보행\s?노인|노인\s?보행',
    '④ 이동권·대중교통': r'수요\s?응답형|DRT|대중교통|이동권|교통\s?약자|교통\s?카드|버스\s?(이용|노선|도입)|택시\s?(지원|이용)',
}
for 유형, 패턴 in 사전.items():
    d[유형] = d['전체글'].str.count(패턴)
유형열 = list(사전)
d['주유형'] = np.where(d[유형열].max(axis=1) >= 2, d[유형열].idxmax(axis=1), '⑤ 기타')
d['관련유형'] = d[유형열].apply(lambda r: ', '.join(k for k in 유형열 if r[k] >= 2), axis=1)

# 2-2) 사람 검수 반영 (자동 분류 결과를 제목·본문으로 하나씩 확인한 뒤 고친 것, 이유를 함께 남긴다)
#   ⑤ 기타에는 '교육·홍보·종합계획'도 포함한다.
검수표 = [
    # (날짜, 제목 일부, 바꿀 값, 이유)  바꿀 값: '제외' 또는 유형 이름
    ('2015-03-24', '마을택시', '④ 이동권·대중교통', '본문을 못 받아 제외됐지만 제목이 농촌 어르신 마을택시·맞춤버스 확대'),
    ('2017-07-09', '교통안전교육', '⑤ 기타', '본문을 못 받아 제외됐지만 고령자 맞춤형 교통안전교육'),
    ('2025-11-12', '안전사고주의보', '⑤ 기타', '본문을 못 받아 제외됐지만 고령자 대중교통 이용 안전 홍보'),
    ('2018-01-08', '정부24', '제외', '어르신 복지 정보 안내 (교통 대책 아님)'),
    ('2018-05-24', '살던 곳에서', '제외', '노인실태조사 결과 (교통 대책 아님)'),
    ('2019-09-10', '노인 일자리', '제외', '노인 일자리 (교통 대책 아님)'),
    ('2020-06-16', '고충 상담', '제외', '운전면허 일반 민원 상담 (고령자 대상 아님)'),
    ('2024-12-03', '인구 비상대책회의', '제외', '공항 교통약자 편의 등 인구정책 일반'),
    ('2020-12-17', '주민센터서 한 번에', '제외', '2020-05-27 면허반납 원스톱 발표를 다시 소개한 정책기자 기사 (중복)'),
    ('2020-09-24', '종합계획', '제외', '2020-09-23 「고령자 교통안전 종합계획」과 같은 계획 (중복)'),
    ('2016-07-05', '손잡다', '⑤ 기타', '교통안전 캠페인 협약 (홍보)'),
    ('2016-08-30', '교통안전교육', '⑤ 기타', '교통안전교육'),
    ('2019-04-14', '교통안전교육', '⑤ 기타', '교통안전교육'),
    ('2016-09-28', '갱신주기 단축', '② 면허·적성', '면허 갱신주기 단축'),
    ('2016-12-15', '택시기사', '② 면허·적성', '고령 택시기사 자격 관리'),
    ('2019-07-04', '협의회', '② 면허·적성', '면허체계 개선 협의회'),
    ('2019-10-17', '인지능력진단', '② 면허·적성', '고령운전자 인지능력 진단'),
]
d['검수'] = ''
for 날짜, 일부, 값, 이유 in 검수표:
    대상행 = (d['날짜'] == 날짜) & d['제목'].str.contains(일부, regex=False)
    assert 대상행.any(), (날짜, 일부)
    if 값 == '제외':
        d.loc[대상행, '제외사유'] = '검수: ' + 이유
    else:
        d.loc[대상행, ['제외사유', '주유형']] = ['', 값]
    d.loc[대상행, '검수'] = 이유
print('검수로 고친 기사:', (d['검수'] != '').sum(), '건')

# 3) 같은 날·같은 부처 묶기
남은 = d[d['제외사유'] == ''].copy()
남은['묶음키'] = 남은['날짜'] + '|' + 남은['부처'].fillna('')
대표 = 남은.sort_values('관련어수', ascending=False).drop_duplicates('묶음키').sort_values('날짜')

print('본문 수집 대상:', len(d))
print('제외:', d['제외사유'].value_counts().to_dict())
print('관련 기사:', len(남은), '→ 같은 날·부처 묶은 뒤:', len(대표))
print('\n주 유형 (묶은 뒤):', 대표['주유형'].value_counts().to_dict())

# 기간별 비교: 팀 분석 기간(2022~2024) vs 전체(2015~2025)
팀기간 = 대표[대표['연도'].between(2022, 2024)]
print('2022~2024 (팀 기간):', len(팀기간), 팀기간['주유형'].value_counts().to_dict())

# 검수표 (사람이 확인할 수 있게 제목·근거 숫자를 함께 저장)
검수 = d[['날짜', '부처', '종류', '제목', '본문출처', '관련어수', '제외사유'] + 유형열 + ['주유형', '관련유형', '검수', '링크']]
검수.to_csv(f'{출력}/분류_검수표.csv', index=False, encoding='utf-8-sig')
대표[['날짜', '부처', '종류', '제목', '주유형', '관련유형', '링크']].to_csv(f'{출력}/최종_대책목록.csv', index=False, encoding='utf-8-sig')

# 그래프: 연도별 주 유형 누적 막대
표 = 대표.pivot_table(index='연도', columns='주유형', values='제목', aggfunc='count', fill_value=0)
표 = 표.reindex(range(2015, 2026), fill_value=0)
색 = {'① 운전자·차량': '#4C72B0', '② 면허·적성': '#55A868', '③ 보행 환경': '#DD8452', '④ 이동권·대중교통': '#C44E52', '⑤ 기타': '#9AA5B1'}
fig, ax = plt.subplots(figsize=(11, 5.5))
아래 = np.zeros(len(표))
for 유형 in [c for c in 색 if c in 표.columns]:
    ax.bar(표.index.astype(str), 표[유형], bottom=아래, color=색[유형], label=유형, zorder=3)
    아래 += 표[유형].values
for x, v in zip(표.index.astype(str), 아래):
    ax.text(x, v + 0.2, f'{int(v)}', ha='center', fontsize=10)
ax.axvspan(6.5, 9.5, color='gold', alpha=0.15, label='팀 분석 기간 (2022~2024)', zorder=0)
ax.set_ylabel('대책 발표 수 (같은 날·부처 묶음)')
ax.set_title(f'정책브리핑 고령자 교통 대책 {len(대표)}건의 연도별 유형 (2015~2025)', fontsize=13, fontweight='bold')
ax.legend(loc='upper left', fontsize=9, ncol=2)
plt.tight_layout()
fig.savefig(f'{출력}/연도별_대책유형.png', dpi=150, facecolor='white')
print(f'\n저장: {출력}/분류_검수표.csv, 최종_대책목록.csv, 연도별_대책유형.png')
