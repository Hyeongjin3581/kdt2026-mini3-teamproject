#                      (평균 반납률 − 해당 시도 반납률) × 65세이상인구 ÷ 1000 으로 추가 반납자 수를 구한다.
# 6-2 (감소 사고 건수): 추가 반납자 수 × (고령사고_만명당 ÷ 10000) 으로 줄어드는 사고 건수를 추정한다.
