sns.scatterplot(data=합계, x='고령화율',
                y='반납률', hue='연도', ax=axs[0])

sns.scatterplot(data=합계, x='정류장_천명당',
                y='반납률', hue='연도', ax=axs[1])

axs[0].set_title('고령화율과 면허 반납률')
