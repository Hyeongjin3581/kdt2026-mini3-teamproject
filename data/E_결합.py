#   · 고령화율 r 강함 / 정류장 r 약함 → "나이 구조가 핵심" → 고령 지역 적성검사·반납 지원 (기각)
#   · 둘 다 강함 → 정류장 r 이 더 크면 채택, 작으면 기각 → 고령화 + 교통 취약 지역 최우선 지원
#   · 연도마다 결과가 다름 → 2개 연도 이상 만족하면 부분 채택, 코로나 영향 여부를 보조 가설로 해석
